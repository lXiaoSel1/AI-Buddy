// Regenerates themes from the portable data extracted from the approved 2026-10-21 design.
// Usage: node scripts/extract-theme-palettes.mjs [--check]
import {readFileSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const source=JSON.parse(readFileSync(join(root,'src/theme-palettes.source.json'),'utf8'));
if(source.schemaVersion!==1||source.approved!=='2026-10-21'||!Array.isArray(source.palettes)||source.palettes.length!==11||!source.ornaments||typeof source.ornaments!=='object')throw Error('Approved theme source data is incomplete');
const {palettes,ornaments}=source;

const body=`// Generated by scripts/extract-theme-palettes.mjs from docs/design/ui-polish-190 (approved 2026-10-21).
// Do not edit by hand: change the design source and run the script again.
const freeze=value=>Object.freeze(Object.fromEntries(Object.entries(value).map(([k,v])=>[k,v&&typeof v==='object'?freeze(v):v])));
export const THEME_PALETTES=Object.freeze(${JSON.stringify(palettes,null,1)}.map(freeze));
`;
const target=join(root,'src/theme-palettes.mjs'),check=process.argv.includes('--check');
if(check){if(readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==body)throw Error('src/theme-palettes.mjs is out of date');}
else writeFileSync(target,body);

// The same palettes as CSS, so a page paints in its theme before any script runs
// (the panel also receives ?theme=). DeepSeek is the :root default.
const {themeVariables}=await import(new URL('../src/appearance.mjs',import.meta.url).href+'?'+Date.now());
// SVG ornaments of the approved (painted-backdrop) variant; the other variants' artwork is left out.
const SIDE_PATTERN={kimi:'--pat-main',gemini:'--pat-main',claude:'--pat-main',hunyuan:'--pat-side'},USED=['--orn-star','--orn-tassel','--orn-film','--orn-sparkles','--orn-flower','--orn-brush','--orn-claw'];
const ornamentVars=id=>{const o=ornaments[id]||{};return (SIDE_PATTERN[id]?';--buddy-side-pattern:'+o[SIDE_PATTERN[id]]:'')+USED.filter(k=>o[k]).map(k=>';--buddy-'+k.slice(2)+':'+o[k]).join('');};
const block=(selector,id)=>selector+'{'+Object.entries(themeVariables(id)).map(([k,v])=>k+':'+v).join(';')+';--buddy-bg-image:url(assets/theme/'+id+'/bg.webp);--buddy-orn-image:url(assets/theme/'+id+'/orn.webp);--buddy-head-image:url(assets/theme/'+id+'/head.webp)'+ornamentVars(id)+'}';
const START='/* @generated theme-tokens: scripts/extract-theme-palettes.mjs */',END='/* @end theme-tokens */';
const region=[START,block(':root','deepseek'),...palettes.map(p=>block(`html[data-theme="${p.id}"]`,p.id)),END].join('\n');
const cssFile=join(root,'src/appearance.css'),css=readFileSync(cssFile,'utf8'),eol=css.includes('\r\n')?'\r\n':'\n';
const i=css.indexOf(START),j=css.indexOf(END);
const nextCss=i>=0&&j>i?css.slice(0,i)+region.replace(/\n/g,eol)+css.slice(j+END.length):region.replace(/\n/g,eol)+eol+css;
if(check){if(nextCss!==css)throw Error('src/appearance.css theme tokens are out of date');console.log('theme palettes and CSS tokens up to date');}
else{writeFileSync(cssFile,nextCss);console.log('wrote',target,'and theme tokens in',cssFile,palettes.length,'themes');}
